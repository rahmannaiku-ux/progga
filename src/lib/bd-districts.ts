/** Older and alternative spellings people type, mapped to the official name. */
const ALIASES: Record<string, string> = {
  barisal: "Barishal",
  chittagong: "Chattogram",
  ctg: "Chattogram",
  comilla: "Cumilla",
  jessore: "Jashore",
  bogra: "Bogura",
  nawabganj: "Chapai Nawabganj",
  "chapainawabganj": "Chapai Nawabganj",
  maulvibazar: "Moulvibazar",
  netrakona: "Netrokona",
  jhalakati: "Jhalokati",
  "coxs bazar": "Cox's Bazar",
  "cox bazar": "Cox's Bazar",
};

const plain = (s: string) => s.toLowerCase().replace(/[^a-zঀ-৿ ]+/g, "").replace(/\s+/g, " ").trim();

/** Districts matching what was typed (English, old spelling or Bangla), best first. */
export function matchDistricts(query: string): BdDistrict[] {
  const q = plain(query);
  if (!q) return [...BD_DISTRICTS];
  const alias = ALIASES[q];
  const scored = BD_DISTRICTS.map((d) => {
    const n = plain(d.name);
    const score =
      n === q || d.bn === query.trim() || alias === d.name ? 0 : n.startsWith(q) || d.bn.startsWith(query.trim()) ? 1 : n.includes(q) || d.bn.includes(query.trim()) ? 2 : plain(d.division).startsWith(q) ? 3 : 9;
    return { d, score };
  });
  return scored.filter((s) => s.score < 9).sort((a, b) => a.score - b.score || a.d.name.localeCompare(b.d.name)).map((s) => s.d);
}

/** The official name for what was typed (any case, old spelling or Bangla), or null if it isn't a district. */
export function officialDistrictName(input: string): string | null {
  const raw = input.trim();
  if (!raw) return null;
  const q = plain(raw);
  const alias = ALIASES[q];
  if (alias) return alias;
  const hit = BD_DISTRICTS.find((d) => plain(d.name) === q || d.bn === raw);
  return hit ? hit.name : null;
}
